def archive_all():
    manifest=[]
    for root in sorted(WORK.glob('OFtutorial*')):
        path=OUT/(root.name+'-v2512.zip')
        with zipfile.ZipFile(path,'w',zipfile.ZIP_DEFLATED) as z:
            for f in sorted(root.rglob('*')):
                if f.is_file() and allowed(f.relative_to(root)):
                    info=zipfile.ZipInfo((Path(root.name)/f.relative_to(root)).as_posix()); info.external_attr=(0o100755 if f.name.startswith('All') else 0o100644)<<16; info.compress_type=zipfile.ZIP_DEFLATED
                    z.writestr(info,f.read_bytes())
        manifest.append(dict(tutorial=root.name,path='/downloads/programming/'+path.name,size=path.stat().st_size,sha256=hashlib.sha256(path.read_bytes()).hexdigest()))
    (OUT/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
    return manifest
if __name__=='__main__': print(json.dumps(archive_all(),indent=2))
