def allowed(rel):
    parts=rel.parts
    if any(p.startswith(('processor','linux64','darwin','win64')) or p in ('lnInclude','postProcessing','VTK','.git','polyMesh','dynamicCode') for p in parts): return False
    if 'testCase' in parts:
        i=parts.index('testCase')
        if len(parts)>i+1 and re.fullmatch(r'[0-9]+(?:\.[0-9]+)?',parts[i+1]) and parts[i+1]!='0': return False
    if rel.name.startswith(('log.','log_')) or rel.suffix.lower() in ('.o','.so','.dep','.vtk','.vtu','.vtp','.vtm','.mp4','.foam','.openfoam'): return False
    if rel.name in ('result','customOutputFile.dat'): return False
    return True

